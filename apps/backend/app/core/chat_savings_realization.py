"""Preserve savings stages and evaluate an explicitly supplied realization rule.

Only complete user-labelled amounts with a common currency/time unit and the
verified/identified percentage formula qualify. No equation or stage assignment
is generated by the model. This is not evidence of actual achieved savings.
"""
import hashlib
import json
import re
from decimal import Decimal, localcontext
from fractions import Fraction

from app.core.chat_rules import normalized

NUMBER = r'[0-9]{1,12}(?:[.,][0-9]{1,12})?'
UNIT = r'(?:EUR|USD|GBP|CHF|CAD|AUD|JPY)(?:/(?:mes|d[ií]a|hora|a[nñ]o))?'
FIELD = re.compile(rf'ahorro (?P<role>identificado|implementado estimado|verificado) '
                   rf'(?P<value>{NUMBER}) (?P<unit>{UNIT})', re.I)
SCENARIO = re.compile(
    r'(?:Contexto del escenario:\s*)?Escenario sint[eé]tico: (?P<fields>[^\n]+)[.] '
    r'Para este ejercicio, (?P<formula>(?:savings )?realization\s*=\s*verificado\s*/\s*'
    r'identificado\s*[*×]\s*100)[.]?', re.I)


def required_savings_realization(catalog):
    question = getattr(catalog, 'classification_question', '')
    parts = question.split('\n\n')
    if len(parts) != 2 or not re.fullmatch(
            r'¿?(?:cuanto ahorro (?:hemos conseguido|se ha realizado|se ha verificado)'
            r'(?: con las recomendaciones)?|calcula (?:el )?(?:ahorro realizado|savings realization|realization))'
            r'[?.]?', normalized(parts[0])):
        return None
    declaration = SCENARIO.fullmatch(parts[1])
    if declaration is None:
        return None
    if any(source.get('kind') != 'corpus' for source in getattr(catalog, 'authorized_sources', ())):
        return None  # Do not replace server financial observations with a scenario.
    fields = declaration['fields'].split('; ')
    if len(fields) != 3:
        return None
    amounts, spans, units = {}, {}, set()
    for field in fields:
        match = FIELD.fullmatch(field)
        if match is None:
            return None
        role = normalized(match['role'])
        if role in amounts:
            return None
        value = Decimal(match['value'].replace(',', '.'))
        if value > Decimal('1e12'):
            return None
        amounts[role] = value
        spans[role] = match.group()
        # No time or currency conversion: normalize observed spelling only.
        unit = normalized(match['unit'])
        units.add(unit)
    if set(amounts) != {'identificado', 'implementado estimado', 'verificado'} or len(units) != 1:
        return None
    raw_unit = next(iter(units)).split('/')
    period = {'dia': 'día', 'ano': 'año'}.get(raw_unit[-1], raw_unit[-1])
    unit = raw_unit[0].upper() + ('/' + period if len(raw_unit) == 2 else '')
    with localcontext() as precision:
        precision.prec = 40
        ratio = amounts['verificado'] / amounts['identificado'] * 100 if amounts['identificado'] else None
    payload = {'question': question, 'source_spans': spans, 'formula': declaration['formula']}
    identity = hashlib.sha256(json.dumps(payload, ensure_ascii=False, sort_keys=True,
                                         separators=(',', ':')).encode()).hexdigest()
    return {'id': identity, 'amounts': amounts, 'unit': unit, 'realization': ratio,
            'source_spans': spans, 'formula_span': declaration['formula']}


def savings_realization_answer(value, catalog):
    bound = required_savings_realization(catalog)
    if bound is None or value != {'savings_realization': bound['id']}:
        raise ValueError('Savings realization is not grounded.')

    def show(number):
        text = format(number, 'f')
        return text.rstrip('0').rstrip('.') if '.' in text else text

    amounts, unit = bound['amounts'], bound['unit']
    identified, estimated, verified = (show(amounts[role]) for role in (
        'identificado', 'implementado estimado', 'verificado'))
    text = ('Escenario hipotético aportado; no verificado financieramente.\n'
            f'Ahorro identificado: {identified} {unit}. '
            f'Ahorro implementado estimado: {estimated} {unit}. '
            f'Ahorro verificado según el escenario: {verified} {unit}.\n'
            f'Para este ejercicio, el ahorro realizado corresponde sólo al verificado: {verified} {unit}. '
            'El identificado y el implementado estimado son etapas distintas; '
            'no se suman ni se presentan como ahorro realizado.\n')
    if bound['realization'] is None:
        text += ('Realization indefinida: el ahorro identificado, denominador de la fórmula '
                 'aportada, es cero. No se inventa un porcentaje de realización.\n')
    else:
        from app.core.chat_expressions import display
        with localcontext() as precision:
            precision.prec = 80
            percentage = display(bound['realization'])
        relation = '=' if Fraction(Decimal(percentage)) * Fraction(amounts['identificado']) == Fraction(amounts['verificado']) * 100 else '≈'
        text += (f'Aplicando la fórmula aportada (verificado / identificado × 100): '
                 f'{verified} / {identified} × 100 {relation} {percentage} %.\n')
    return text + ('Esto no acredita ahorro real ni valida su causa, comparabilidad o período de medición. '
                   'Para confirmarlo hacen falta evidencias de ahorro y costes autorizadas '
                   'para el mismo ámbito y período, con una base de comparación consistente.')
